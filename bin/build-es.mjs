#!/usr/bin/env node
/**
 * bin/build-es.mjs — generates es/index.html (real Spanish HTML) from index.html.
 *
 * Why this exists: Google treats /?lang=es as a duplicate of / and ignores the
 * hreflang="es" hint, so the Spanish version never ranks on its own URL. ES needs
 * a separate URL that serves Spanish HTML on the server side, not JS-swapped text.
 *
 * This is the deliberate exception to SPEC's "no build steps" rule: it is a single
 * ~50-line script, no bundler, no webpack, no babel, no npm dependencies — only
 * node:fs, node:path and node:vm.
 *
 * Contract:
 *   - reads  index.html (never writes it)
 *   - writes es/index.html
 *   - idempotent: es/index.html is always regenerated from scratch, so running it
 *     twice in a row produces byte-identical output
 *   - an unknown data-i18n key is a WARN (original text kept), never a crash
 *
 * Usage: node bin/build-es.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_PATH = path.join(ROOT, 'index.html');
const OUT_DIR = path.join(ROOT, 'es');
const OUT_PATH = path.join(OUT_DIR, 'index.html');

const ORIGIN = 'https://localjson-black.vercel.app';
const ES_URL = `${ORIGIN}/es/`;

const BANNER =
  '<!-- AUTO-GENERATED by bin/build-es.mjs from index.html — do not edit by hand; ' +
  'edit the source and the ES dictionary, then re-run the generator. -->';

let warnings = 0;
const warn = (msg) => {
  warnings += 1;
  console.warn(`[build-es] WARN  ${msg}`);
};
const note = (msg) => console.log(`[build-es] note  ${msg}`);
const info = (msg) => console.log(`[build-es] ${msg}`);
const fail = (msg) => {
  console.error(`[build-es] ERROR ${msg}`);
  process.exit(1);
};

/* ------------------------------------------------------------------ helpers */

// textContent semantics: escape what would otherwise be markup
const escapeText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// attribute semantics: also escape quotes and turn real newlines into &#10;
const escapeAttr = (s) => escapeText(s).replace(/"/g, '&quot;').replace(/\n/g, '&#10;');

/** Set (or insert) an attribute inside an already-rendered opening tag. */
function setAttr(tagStr, name, value) {
  const escaped = escapeAttr(value);
  // Match the existing attribute whatever its quoting (the source has both
  // placeholder="x" and placeholder='x') and normalise it to double quotes.
  // A regex that only knew about ="..." would insert a SECOND attribute, and
  // HTML keeps the first one — leaving English text on the Spanish page.
  const re = new RegExp(`(\\s${name}=)(?:"[^"]*"|'[^']*'|[^\\s>]+)`);
  if (re.test(tagStr)) return tagStr.replace(re, (_m, p1) => `${p1}"${escaped}"`);
  const selfClosing = tagStr.endsWith('/>');
  const head = selfClosing ? tagStr.slice(0, -2) : tagStr.slice(0, -1);
  const tail = selfClosing ? '/>' : '>';
  return `${head} ${name}="${escaped}"${tail}`;
}

/** Index of the closing tag matching the element whose content starts at `from`. */
function findMatchingClose(html, from, tag) {
  const re = new RegExp(`<${tag}\\b[^>]*>|</${tag}\\s*>`, 'gi');
  re.lastIndex = from;
  let depth = 1;
  let m;
  while ((m = re.exec(html)) !== null) {
    if (m[0].startsWith('</')) {
      depth -= 1;
      if (depth === 0) return { start: m.index, end: m.index + m[0].length };
    } else {
      depth += 1;
    }
  }
  return null;
}

/** Replace exactly once, but refuse to emit a half-built page if the source moved. */
function replaceOnce(html, re, replacement, label) {
  if (!re.test(html)) {
    fail(`cannot find ${label} in index.html — source changed, refusing to write a partial ES page`);
  }
  return html.replace(re, replacement);
}

/* --------------------------------------------------------- I18N extraction */

function extractDicts(html) {
  const blocks = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map((m) => m[1]);
  const block = blocks.find((code) => /\bI18N\s*=/.test(code));
  if (!block) fail('I18N block not found in index.html');

  // The dictionary script only touches `window`, so an isolated context is enough.
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  try {
    vm.runInContext(block, sandbox, { timeout: 5000 });
  } catch (err) {
    fail(`could not evaluate the I18N script block: ${err.message}`);
  }

  const i18n = sandbox.window && sandbox.window.I18N;
  if (!i18n || !i18n.es) fail('window.I18N.es not found in index.html (ES dictionary is missing)');
  if (!i18n.en) warn('window.I18N.en not found — the English-leftover self-check will be limited');
  return { es: i18n.es, en: i18n.en || {} };
}

/* ---------------------------------------------------------------- transforms */

const ELEMENT_RE = /<([a-zA-Z][a-zA-Z0-9-]*)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>/g;
const ATTR_ELEMENT_RE = /<([a-zA-Z][a-zA-Z0-9-]*)\b[^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/g;

/** data-i18n -> textContent (or placeholder for input/textarea), like applyLang did. */
function translateElements(html, dict) {
  const matches = [...html.matchAll(ELEMENT_RE)];
  let translated = 0;

  // Walk backwards so earlier offsets stay valid while we splice.
  for (let i = matches.length - 1; i >= 0; i -= 1) {
    const m = matches[i];
    const tag = m[1].toLowerCase();
    const key = m[2];
    const value = dict[key];

    if (typeof value !== 'string') {
      warn(`no ES translation for data-i18n="${key}" on <${tag}> — original text kept`);
      continue;
    }

    const openStart = m.index;
    const openEnd = m.index + m[0].length;

    if (tag === 'input' || tag === 'textarea') {
      const newTag = setAttr(m[0], 'placeholder', value);
      html = html.slice(0, openStart) + newTag + html.slice(openEnd);
      translated += 1;
      continue;
    }

    const close = findMatchingClose(html, openEnd, tag);
    if (!close) {
      warn(`no closing </${tag}> found for data-i18n="${key}" — original text kept`);
      continue;
    }
    const inner = html.slice(openEnd, close.start);
    if (inner.includes('<')) {
      // applyLang() assigns textContent at runtime, so the live page drops this
      // markup too; the static page must match it or English text would survive.
      note(
        `data-i18n="${key}" on <${tag}> contains inline markup (${inner.match(/<[a-zA-Z][^>]*>/g).join(', ')}) — ` +
          'replaced by plain text, exactly as the runtime textContent assignment does'
      );
    }

    html = html.slice(0, openEnd) + escapeText(value) + html.slice(close.start);
    translated += 1;
  }

  return { html, translated, total: matches.length };
}

/** data-i18n-attr="KEY:ATTR[,KEY2:ATTR2]" -> set that attribute. */
function translateAttrs(html, dict) {
  const matches = [...html.matchAll(ATTR_ELEMENT_RE)];
  let translated = 0;

  for (let i = matches.length - 1; i >= 0; i -= 1) {
    const m = matches[i];
    const tag = m[1].toLowerCase();
    const pairs = m[2].split(',').map((s) => s.trim()).filter(Boolean);
    let tagStr = m[0];
    let changed = false;

    for (const pair of pairs) {
      const [key, attr] = pair.split(':').map((s) => (s || '').trim());
      if (!key || !attr) {
        warn(`malformed data-i18n-attr entry "${pair}" on <${tag}> — skipped`);
        continue;
      }
      const value = dict[key];
      if (typeof value !== 'string') {
        warn(`no ES translation for data-i18n-attr key "${key}" on <${tag}> — original kept`);
        continue;
      }
      tagStr = setAttr(tagStr, attr, value);
      changed = true;
      translated += 1;
    }

    if (changed && tagStr !== m[0]) {
      html = html.slice(0, m.index) + tagStr + html.slice(m.index + m[0].length);
    }
  }

  return { html, translated, total: matches.length };
}

/** Drop whole <script> blocks matching a predicate (the JS language layer). */
function removeScriptBlocks(html, predicate, label) {
  const re = /[ \t]*<script\b[^>]*>[\s\S]*?<\/script>\n?/gi;
  const targets = [...html.matchAll(re)].filter((m) => predicate(m[0]));
  if (targets.length === 0) fail(`cannot find the ${label} script block in index.html`);
  if (targets.length > 1) warn(`found ${targets.length} ${label} script blocks — removing all of them`);
  for (let i = targets.length - 1; i >= 0; i -= 1) {
    const m = targets[i];
    html = html.slice(0, m.index) + html.slice(m.index + m[0].length);
  }
  return html;
}

/**
 * Shrink the inline I18N dictionary down to the keys this static page still needs.
 *
 * The page is static Spanish once this generator is done, so the full EN+ES
 * dictionary is dead weight — and worse, it puts English strings (the EN title,
 * the EN documentation links) back into a Spanish page that the SEO checks then
 * read as leftovers. Two sets survive:
 *
 *   1. keys the surviving inline script actually looks up at runtime, and
 *   2. keys the markup itself declares through data-i18n-attr,
 *
 * so the page stays self-describing for anything that re-applies translations
 * later. Everything referenced only by a baked data-i18n text is dropped: those
 * strings are already in the markup, and keeping them would leave a second copy
 * of the Spanish <title> in the file.
 */
function minimiseInlineDict(html, dict) {
  const referenced = new Set();

  const lookup = /window\.I18N\s*\[[^\]]*\]\s*\[\s*['"]([^'"]+)['"]\s*\]/g;
  let m;
  while ((m = lookup.exec(html)) !== null) referenced.add(m[1]);

  const declared = /data-i18n-attr="([^"]*)"/g;
  while ((m = declared.exec(html)) !== null) {
    for (const pair of m[1].split(',')) {
      const key = (pair.split(':')[0] || '').trim();
      if (key) referenced.add(key);
    }
  }

  const keep = {};
  for (const key of referenced) {
    if (typeof dict[key] === 'string') {
      keep[key] = dict[key];
    } else {
      warn(`the ES page references "${key}", which has no ES value — it will be undefined`);
    }
  }

  const re = /<script\b[^>]*>[\s\S]*?<\/script>/gi;
  const block = [...html.matchAll(re)].find((b) => /const\s+I18N\s*=/.test(b[0]));
  if (!block) fail('cannot find the inline I18N dictionary in the generated page');

  const body = JSON.stringify({ es: keep }, null, 4).replace(/\n/g, '\n        ');
  const replacement =
    '    <script>\n' +
    '        // Static Spanish page: the markup already carries the translations, so\n' +
    '        // only the keys the inline script reads and the markup declares as\n' +
    '        // attributes are kept; every other translation lives in the HTML itself.\n' +
    `        window.I18N = ${body};\n` +
    '    </script>';

  note(`inline dictionary reduced from ${Object.keys(dict).length} keys to ${Object.keys(keep).length} (${Object.keys(keep).join(', ') || 'none'})`);
  return html.slice(0, block.index) + replacement + html.slice(block.index + block[0].length);
}

/* --------------------------------------------------------------------- main */

function build() {
  if (!fs.existsSync(SRC_PATH)) fail(`index.html not found at ${SRC_PATH}`);
  let html = fs.readFileSync(SRC_PATH, 'utf8');
  const before = html.length;

  const { es: dict, en: enDict } = extractDicts(html);

  // 1-5. Bake the Spanish dictionary into the static markup.
  const elements = translateElements(html, dict);
  html = elements.html;
  const attrs = translateAttrs(html, dict);
  html = attrs.html;

  // 6. document language
  html = replaceOnce(html, /<html lang="[^"]*">/, '<html lang="es">', '<html lang="...">');

  // 7. canonical -> /es/
  html = replaceOnce(
    html,
    /(<link rel="canonical" href=")[^"]*(")/,
    (_m, p1, p2) => p1 + ES_URL + p2,
    'the canonical link'
  );

  // 8. hreflang: en -> /, es -> /es/, x-default -> /
  html = replaceOnce(
    html,
    /(<link rel="alternate" hreflang="en" href=")[^"]*(")/,
    (_m, p1, p2) => p1 + ORIGIN + '/' + p2,
    'the hreflang="en" link'
  );
  html = replaceOnce(
    html,
    /(<link rel="alternate" hreflang="es" href=")[^"]*(")/,
    (_m, p1, p2) => p1 + ES_URL + p2,
    'the hreflang="es" link'
  );
  html = replaceOnce(
    html,
    /(<link rel="alternate" hreflang="x-default" href=")[^"]*(")/,
    (_m, p1, p2) => p1 + ORIGIN + '/' + p2,
    'the hreflang="x-default" link'
  );

  // 9. og:url -> /es/
  html = replaceOnce(
    html,
    /(<meta property="og:url" content=")[^"]*(")/,
    (_m, p1, p2) => p1 + ES_URL + p2,
    'the og:url meta tag'
  );

  // 10. the language switch becomes two plain links (no JS, crawlable)
  html = replaceOnce(
    html,
    /<div style="display: flex; gap: 8px;">\s*<button class="lang-btn" data-lang="en"[\s\S]*?data-lang="es"[^>]*>ES<\/button>\s*<\/div>/,
    `            <div style="display: flex; gap: 8px;">
                <a href="/" class="lang-btn" style="display: inline-flex; align-items: center; justify-content: center; text-decoration: none; color: #64748b;">EN</a>
                <a href="/es/" class="lang-btn" aria-current="page" style="display: inline-flex; align-items: center; justify-content: center; text-decoration: none; color: #e2e8f0;">ES</a>
            </div>`,
    'the language switch block'
  );

  // 11a. drop the FOUC-prevention language script (initLang/applyLang): the page is
  //      already Spanish, and leaving it in would let a stale localStorage override it.
  html = removeScriptBlocks(html, (block) => /initLang\s*\(/.test(block), 'initLang/applyLang');
  // 11b. drop the click handlers + apply-on-load inside the main script. The
  //      ?auth=success / checkProStatus logic in the same listener stays.
  html = replaceOnce(
    html,
    /\n[ \t]*\/\/ Language switcher click handlers[\s\S]*?document\.documentElement\.lang = lang;\n/,
    '\n',
    'the language click handler block'
  );

  // 12. shrink the inline dictionary to what the surviving script actually reads
  html = minimiseInlineDict(html, dict);

  // 13. provenance banner (after the doctype, so the doctype stays first)
  html = replaceOnce(html, /<!DOCTYPE html>\n/, `<!DOCTYPE html>\n${BANNER}\n`, 'the doctype');

  // ---- self-check: never write a page that is still half-English in the head ----
  const problems = [];
  const count = (re) => (html.match(re) || []).length;
  if (count(/<html lang="es">/g) !== 1) problems.push('expected exactly one <html lang="es">');
  if (count(/<html lang="en">/g) !== 0) problems.push('<html lang="en"> still present');
  if (count(new RegExp(`<link rel="canonical" href="${ES_URL.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`, 'g')) !== 1) {
    problems.push('canonical is not exactly one /es/ link');
  }
  if (count(new RegExp(`<link rel="alternate" hreflang="es" href="${ES_URL.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`, 'g')) !== 1) {
    problems.push('hreflang="es" does not point at exactly one /es/ link');
  }
  if (count(/data-lang="/g) !== 0) problems.push('language toggle buttons (data-lang) still present');
  if (/initLang\s*\(/.test(html)) problems.push('initLang() still present');
  if (/window\.applyLang/.test(html)) problems.push('window.applyLang is still referenced but its definition was removed');
  if (/window\.I18N\[document\.documentElement\.lang/.test(html) === false && /checkProStatus/.test(html)) {
    warn('checkProStatus no longer reads window.I18N — check the Pro button label manually');
  }
  const bareI18N = html.replace(/window\.I18N/g, '').match(/.{0,60}\bI18N\b.{0,60}/s);
  if (bareI18N) {
    problems.push(`a bare I18N identifier survived while the dictionary is no longer declared: …${bareI18N[0].trim()}…`);
  }

  // No English leftovers: the ES page must not carry the EN head strings or the
  // EN documentation links anywhere, dictionary included.
  for (const key of ['meta-title', 'meta-description', 'og-title', 'og-description', 'footer-offline-href', 'footer-pro-docs-href']) {
    const en = enDict[key];
    if (typeof en === 'string' && html.includes(en)) {
      problems.push(`the English value of "${key}" is still present in the Spanish page`);
    }
  }
  if (problems.length) fail(`self-check failed: ${problems.join('; ')}`);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_PATH, html, 'utf8');

  const missing = Object.keys(dict).length;
  info(`translated ${elements.translated}/${elements.total} data-i18n elements, ${attrs.translated} data-i18n-attr attributes`);
  info(`ES dictionary keys: ${missing}`);
  info(`index.html ${before} bytes -> es/index.html ${Buffer.byteLength(html, 'utf8')} bytes`);
  info(warnings === 0 ? 'no warnings' : `${warnings} warning(s)`);
}

build();
