#!/usr/bin/env node
/**
 * bin/build-blog.mjs — generates blog article pages and blog index from Markdown.
 *
 * Contract:
 *   - reads blog/posts/*.md (never writes them)
 *   - writes blog/<slug>/index.html and blog/index.html
 *   - updates sitemap.xml with new blog URLs
 *   - idempotent: running twice produces byte-identical output
 *   - missing required frontmatter field → ERROR, no partial write
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const POSTS_DIR = path.join(ROOT, 'blog', 'posts');
const TEMPLATE_PATH = path.join(ROOT, 'blog', 'template.html');
const BLOG_DIR = path.join(ROOT, 'blog');
const SITEMAP_PATH = path.join(ROOT, 'sitemap.xml');

const ORIGIN = 'https://localjson-black.vercel.app';
const BLOG_URL = `${ORIGIN}/blog/`;

const BANNER = '<!-- AUTO-GENERATED by bin/build-blog.mjs from blog/posts/*.md — do not edit by hand; edit the source Markdown and re-run the generator. -->';

let warnings = 0;
const warn = (msg) => {
    warnings += 1;
    console.warn(`[build-blog] WARN  ${msg}`);
};
const info = (msg) => console.log(`[build-blog] ${msg}`);
const fail = (msg) => {
    console.error(`[build-blog] ERROR ${msg}`);
    process.exit(1);
};

/* ------------------------------------------------------------------ frontmatter parsing */

function parseFrontmatter(content) {
    const fmMatch = content.match(/^---\n([\s\S]*?)\n---/);
    if (!fmMatch) return { frontmatter: null, body: content };
    const fmText = fmMatch[1];
    const body = content.slice(fmMatch[0].length).trimStart();
    const frontmatter = {};
    for (const line of fmText.split('\n')) {
        const colon = line.indexOf(':');
        if (colon === -1) continue;
        const key = line.slice(0, colon).trim();
        let value = line.slice(colon + 1).trim();
        // Handle arrays (keywords: ["a", "b"])
        if (value.startsWith('[') && value.endsWith(']')) {
            try {
                value = JSON.parse(value);
            } catch {
                // fallback: comma-separated
                value = value.slice(1, -1).split(',').map(s => s.trim().replace(/^["']|["']$/g, ''));
            }
        } else if (value.startsWith('"') && value.endsWith('"') || value.startsWith("'") && value.endsWith("'")) {
            value = value.slice(1, -1);
        }
        frontmatter[key] = value;
    }
    return { frontmatter, body };
}

const REQUIRED_FIELDS = ['slug', 'title', 'description', 'date', 'author', 'cluster', 'keywords'];

/* ------------------------------------------------------------------ Markdown to HTML */

function escapeHtml(str) {
    return str
        .replace(/&/g, '&')
        .replace(/</g, '<')
        .replace(/>/g, '>')
        .replace(/"/g, '"')
        .replace(/'/g, '&apos;');
}

function parseInline(text, slugMap) {
    // Order matters: code before bold/italic, links before plain
    let html = escapeHtml(text);

    // Internal links [[slug]] or [[slug|text]] — process BEFORE escaping
    // We need to handle this on the raw text, so let's do a different approach
    // Actually, let's parse inline on raw text with a state machine approach
    return parseInlineRaw(text, slugMap);
}

function parseInlineRaw(text, slugMap) {
    // First, handle internal links [[slug|text]] or [[slug]]
    let result = text.replace(/\[\[([^\]]+)\]\]/g, (match, content) => {
        const [slug, label] = content.split('|').map(s => s.trim());
        const target = slugMap.get(slug);
        if (!target) {
            warn(`internal link to unknown slug "${slug}" — rendered as plain text`);
            return content; // plain text fallback
        }
        const linkText = label || target.title;
        return `<a href="/blog/${slug}/">${escapeHtml(linkText)}</a>`;
    });

    // Now escape HTML, but preserve the <a> tags we just created
    // Split by <a> tags, escape the parts, reassemble
    const parts = result.split(/(<a href="\/blog\/[^"]+">[^<]+<\/a>)/);
    for (let i = 0; i < parts.length; i++) {
        if (!parts[i].startsWith('<a href=')) {
            parts[i] = escapeHtml(parts[i]);
        }
    }
    result = parts.join('');

    // Code spans `code`
    result = result.replace(/`([^`]+)`/g, '<code>$1</code>');

    // Bold **text**
    result = result.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');

    // Italic *text* (but not bold already handled)
    result = result.replace(/\*([^*]+)\*/g, '<em>$1</em>');

    // Links [text](url)
    result = result.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

    return result;
}

function markdownToHtml(markdown, slugMap) {
    const lines = markdown.split('\n');
    const htmlLines = [];
    let inCodeBlock = false;
    let codeBlockLang = '';
    let codeBlockContent = [];
    let inList = false;
    let listType = null; // 'ul' or 'ol'
    let listItems = [];

    const flushCodeBlock = () => {
        if (inCodeBlock) {
            const code = codeBlockContent.join('\n');
            const langClass = codeBlockLang ? ` class="language-${codeBlockLang}"` : '';
            htmlLines.push(`<pre><code${langClass}>${escapeHtml(code)}</code></pre>`);
            inCodeBlock = false;
            codeBlockLang = '';
            codeBlockContent = [];
        }
    };

    const flushList = () => {
        if (inList) {
            const tag = listType === 'ol' ? 'ol' : 'ul';
            htmlLines.push(`<${tag}>`);
            for (const item of listItems) {
                htmlLines.push(`<li>${parseInlineRaw(item, slugMap)}</li>`);
            }
            htmlLines.push(`</${tag}>`);
            inList = false;
            listType = null;
            listItems = [];
        }
    };

    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];

        // Code block start/end
        if (line.startsWith('```')) {
            if (!inCodeBlock) {
                flushList();
                inCodeBlock = true;
                codeBlockLang = line.slice(3).trim();
                codeBlockContent = [];
            } else {
                flushCodeBlock();
            }
            continue;
        }

        if (inCodeBlock) {
            codeBlockContent.push(line);
            continue;
        }

        // Headings
        const hMatch = line.match(/^(#{1,3})\s+(.+)$/);
        if (hMatch) {
            flushList();
            const level = hMatch[1].length;
            const text = hMatch[2].trim();
            htmlLines.push(`<h${level}>${parseInlineRaw(text, slugMap)}</h${level}>`);
            continue;
        }

        // Horizontal rule
        if (line.trim() === '---') {
            flushList();
            htmlLines.push('<hr>');
            continue;
        }

        // Blockquote
        const bqMatch = line.match(/^>\s*(.*)$/);
        if (bqMatch) {
            flushList();
            htmlLines.push(`<blockquote>${parseInlineRaw(bqMatch[1], slugMap)}</blockquote>`);
            continue;
        }

        // Lists
        const ulMatch = line.match(/^-\s+(.+)$/);
        const olMatch = line.match(/^(\d+)\.\s+(.+)$/);
        if (ulMatch || olMatch) {
            if (!inList) {
                inList = true;
                listType = ulMatch ? 'ul' : 'ol';
                listItems = [];
            } else if ((ulMatch && listType !== 'ul') || (olMatch && listType !== 'ol')) {
                flushList();
                inList = true;
                listType = ulMatch ? 'ul' : 'ol';
                listItems = [];
            }
            listItems.push(ulMatch ? ulMatch[1] : olMatch[2]);
            continue;
        }

        // If we were in a list and this line doesn't continue it
        if (inList && line.trim() !== '' && !ulMatch && !olMatch) {
            flushList();
        }

        // Paragraphs
        if (line.trim() === '') {
            continue; // blank line separates paragraphs
        }

        // Regular paragraph
        flushList();
        // Collect consecutive non-special lines as one paragraph
        let paraLines = [line];
        let j = i + 1;
        while (j < lines.length) {
            const next = lines[j];
            if (next.trim() === '' || next.startsWith('```') || next.match(/^#{1,3}\s/) || next.match(/^-\s/) || next.match(/^\d+\.\s/) || next.trim() === '---' || next.startsWith('>')) {
                break;
            }
            paraLines.push(next);
            j++;
        }
        i = j - 1;
        const paraText = paraLines.join(' ').trim();
        htmlLines.push(`<p>${parseInlineRaw(paraText, slugMap)}</p>`);
    }

    flushCodeBlock();
    flushList();

    return htmlLines.join('\n');
}

/* ------------------------------------------------------------------ date formatting */

function formatDateHuman(iso) {
    const d = new Date(iso + 'T00:00:00');
    return d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}

/* ------------------------------------------------------------------ JSON-LD */

function buildJsonLd(fm, canonical) {
    const obj = {
        '@context': 'https://schema.org',
        '@type': 'Article',
        headline: fm.title,
        description: fm.description,
        datePublished: fm.date,
        author: { '@type': 'Person', name: fm.author },
        publisher: { '@type': 'Organization', name: 'LocalJSON', url: ORIGIN },
        mainEntityOfPage: { '@type': 'WebPage', '@id': canonical },
        keywords: Array.isArray(fm.keywords) ? fm.keywords.join(', ') : fm.keywords
    };
    return JSON.stringify(obj, null, 2);
}

/* ------------------------------------------------------------------ template rendering */

function renderTemplate(template, fm, bodyHtml, canonical, jsonLd, slug) {
    const keywordsStr = Array.isArray(fm.keywords) ? fm.keywords.join(', ') : fm.keywords;
    return template
        .replace(/\{\{TITLE\}\}/g, escapeHtml(fm.title))
        .replace(/\{\{DESCRIPTION\}\}/g, escapeHtml(fm.description))
        .replace(/\{\{CANONICAL\}\}/g, canonical)
        .replace(/\{\{DATE_ISO\}\}/g, fm.date)
        .replace(/\{\{DATE_HUMAN\}\}/g, formatDateHuman(fm.date))
        .replace(/\{\{CLUSTER\}\}/g, escapeHtml(fm.cluster))
        .replace(/\{\{KEYWORDS\}\}/g, escapeHtml(keywordsStr))
        .replace(/\{\{BODY\}\}/g, bodyHtml)
        .replace(/\{\{JSONLD\}\}/g, jsonLd)
        .replace(/\{\{SLUG\}\}/g, slug);
}

/* ------------------------------------------------------------------ sitemap */

function updateSitemap(posts) {
    const NS = 'http://www.sitemaps.org/schemas/sitemap/0.9';
    const XHTML_NS = 'http://www.w3.org/1999/xhtml';

    // Read existing sitemap and parse loc, lastmod, changefreq, priority
    let existingUrls = [];
    if (fs.existsSync(SITEMAP_PATH)) {
        const content = fs.readFileSync(SITEMAP_PATH, 'utf8');
        const urlBlocks = content.matchAll(/<url>([\s\S]*?)<\/url>/g);
        for (const block of urlBlocks) {
            const locMatch = block[1].match(/<loc>([^<]+)<\/loc>/);
            const lastmodMatch = block[1].match(/<lastmod>([^<]+)<\/lastmod>/);
            const changefreqMatch = block[1].match(/<changefreq>([^<]+)<\/changefreq>/);
            const priorityMatch = block[1].match(/<priority>([^<]+)<\/priority>/);
            if (locMatch) {
                existingUrls.push({
                    loc: locMatch[1],
                    lastmod: lastmodMatch ? lastmodMatch[1] : new Date().toISOString().slice(0,10),
                    changefreq: changefreqMatch ? changefreqMatch[1] : 'weekly',
                    priority: priorityMatch ? priorityMatch[1] : '0.5'
                });
            }
        }
    }

    // Build new URL set: keep existing non-blog URLs, replace blog URLs
    const keepUrls = existingUrls.filter(u => !u.loc.includes('/blog/'));
    const blogUrls = posts.map(p => ({
        loc: `${BLOG_URL}${p.slug}/`,
        lastmod: p.date,
        changefreq: 'monthly',
        priority: '0.8'
    }));

    // Also add /blog/ index
    blogUrls.unshift({
        loc: BLOG_URL,
        lastmod: posts.length > 0 ? posts[0].date : new Date().toISOString().slice(0,10),
        changefreq: 'weekly',
        priority: '0.9'
    });

    const allUrls = [...keepUrls, ...blogUrls];

    let xml = '<?xml version="1.0" encoding="UTF-8"?>\n';
    xml += `<urlset xmlns="${NS}" xmlns:xhtml="${XHTML_NS}">\n`;

    for (const u of allUrls) {
        xml += '  <url>\n';
        xml += `    <loc>${u.loc}</loc>\n`;
        xml += `    <lastmod>${u.lastmod}</lastmod>\n`;
        xml += `    <changefreq>${u.changefreq}</changefreq>\n`;
        xml += `    <priority>${u.priority}</priority>\n`;
        // Add hreflang for known URLs
        if (u.loc === ORIGIN + '/' || u.loc === BLOG_URL) {
            xml += `    <xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}/"/>\n`;
            xml += `    <xhtml:link rel="alternate" hreflang="es" href="${ORIGIN}/es/"/>\n`;
            xml += `    <xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}/"/>\n`;
        } else if (u.loc === ORIGIN + '/es/') {
            xml += `    <xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}/"/>\n`;
            xml += `    <xhtml:link rel="alternate" hreflang="es" href="${ORIGIN}/es/"/>\n`;
            xml += `    <xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}/"/>\n`;
        }
        xml += '  </url>\n';
    }

    xml += '</urlset>\n';
    fs.writeFileSync(SITEMAP_PATH, xml, 'utf8');
    info(`sitemap.xml updated (${allUrls.length} URLs)`);
}

/* ------------------------------------------------------------------ blog index generation */

function generateBlogIndex(posts, template) {
    // Sort by date descending
    const sorted = [...posts].sort((a, b) => b.date.localeCompare(a.date));

    let itemsHtml = '';
    for (const p of sorted) {
        itemsHtml += `
            <article style="background: var(--card); border: 1px solid var(--border); border-radius: 12px; padding: 1.5rem; margin-bottom: 1rem;">
                <h2 style="font-size: 1.25rem; font-weight: 600; margin-bottom: 0.5rem;">
                    <a href="/blog/${p.slug}/" style="color: var(--fg);">${escapeHtml(p.title)}</a>
                </h2>
                <p style="color: var(--fg-muted); margin-bottom: 0.75rem;">${escapeHtml(p.description)}</p>
                <div style="display: flex; align-items: center; gap: 1rem; font-size: 0.875rem; color: var(--fg-muted); flex-wrap: wrap;">
                    <time datetime="${p.date}">${formatDateHuman(p.date)}</time>
                    <span class="cluster" style="background: var(--bg); padding: 0.125rem 0.5rem; border-radius: 999px; font-size: 0.75rem; border: 1px solid var(--border);">${escapeHtml(p.cluster)}</span>
                </div>
                <a href="/blog/${p.slug}/" style="display: inline-block; margin-top: 0.75rem; color: var(--accent); font-size: 0.875rem;">Read →</a>
            </article>
        `;
    }

    const today = new Date().toISOString().slice(0,10);
    const indexTemplate = template
        .replace(/\{\{TITLE\}\}/g, 'Blog')
        .replace(/\{\{DESCRIPTION\}\}/g, 'Latest articles on JSON tooling, validation, conversion, and B2B data workflows.')
        .replace(/\{\{CANONICAL\}\}/g, BLOG_URL)
        .replace(/\{\{DATE_ISO\}\}/g, today)
        .replace(/\{\{DATE_HUMAN\}\}/g, formatDateHuman(today))
        .replace(/\{\{CLUSTER\}\}/g, 'blog')
        .replace(/\{\{KEYWORDS\}\}/g, 'json, formatter, validator, converter, schema, b2b')
        .replace(/\{\{BODY\}\}/g, `
            <nav class="breadcrumbs" aria-label="Breadcrumb">
                <a href="/">Home</a>
                <span>/</span>
                <span aria-current="page">Blog</span>
            </nav>
            <h1 style="font-size: 2rem; font-weight: 700; margin-bottom: 2rem;">Blog</h1>
            <div>${itemsHtml}</div>
        `)
        .replace(/\{\{JSONLD\}\}/g, JSON.stringify({
            '@context': 'https://schema.org',
            '@type': 'Blog',
            name: 'LocalJSON Blog',
            url: BLOG_URL,
            blogPosts: sorted.map(p => ({
                '@type': 'BlogPosting',
                headline: p.title,
                url: `${BLOG_URL}${p.slug}/`,
                datePublished: p.date
            }))
        }, null, 2))
        .replace(/\{\{SLUG\}\}/g, '')
        // Fix double slash in ES hreflang for index page
        .replace(/\/es\/blog\/\//g, '/es/blog/');

    return indexTemplate;
}

/* ------------------------------------------------------------------ main */

function build() {
    if (!fs.existsSync(POSTS_DIR)) fail(`blog/posts directory not found at ${POSTS_DIR}`);
    if (!fs.existsSync(TEMPLATE_PATH)) fail(`blog/template.html not found at ${TEMPLATE_PATH}`);

    const template = fs.readFileSync(TEMPLATE_PATH, 'utf8');

    const files = fs.readdirSync(POSTS_DIR).filter(f => f.endsWith('.md'));
    if (files.length === 0) {
        warn('no Markdown posts found in blog/posts/');
    }

    const posts = [];
    const slugMap = new Map(); // slug -> { title, ... }
    const seenSlugs = new Set();

    for (const file of files) {
        const content = fs.readFileSync(path.join(POSTS_DIR, file), 'utf8');
        const { frontmatter, body } = parseFrontmatter(content);

        if (!frontmatter) {
            fail(`no frontmatter found in ${file}`);
        }

        // Validate required fields
        for (const field of REQUIRED_FIELDS) {
            if (!frontmatter[field] || (Array.isArray(frontmatter[field]) && frontmatter[field].length === 0)) {
                fail(`missing required field "${field}" in ${file}`);
            }
        }

        const slug = frontmatter.slug;
        if (seenSlugs.has(slug)) {
            fail(`duplicate slug "${slug}" found in ${file}`);
        }
        seenSlugs.add(slug);

        // Validate slug format
        if (!/^[a-z0-9-]+$/.test(slug)) {
            fail(`invalid slug "${slug}" in ${file} — must be lowercase, hyphens only`);
        }

        // Convert Markdown to HTML
        const bodyHtml = markdownToHtml(body, slugMap);

        // Count internal links
        const internalLinkCount = (body.match(/\[\[[^\]]+\]\]/g) || []).length;
        if (internalLinkCount === 0) {
            warn(`post "${slug}" has 0 internal links`);
        }

        const canonical = `${BLOG_URL}${slug}/`;
        const jsonLd = buildJsonLd(frontmatter, canonical);
        const pageHtml = renderTemplate(template, frontmatter, bodyHtml, canonical, jsonLd, slug);

        const outDir = path.join(BLOG_DIR, slug);
        fs.mkdirSync(outDir, { recursive: true });
        const outPath = path.join(outDir, 'index.html');
        fs.writeFileSync(outPath, pageHtml, 'utf8');
        info(`generated ${outPath}`);

        posts.push({
            slug,
            title: frontmatter.title,
            description: frontmatter.description,
            date: frontmatter.date,
            cluster: frontmatter.cluster,
            canonical
        });

        slugMap.set(slug, { title: frontmatter.title, ...frontmatter });
    }

    // Generate blog index
    const indexHtml = generateBlogIndex(posts, template);
    fs.writeFileSync(path.join(BLOG_DIR, 'index.html'), indexHtml, 'utf8');
    info(`generated blog/index.html (${posts.length} posts)`);

    // Update sitemap
    updateSitemap(posts);

    info(warnings === 0 ? 'no warnings' : `${warnings} warning(s)`);
}

build();